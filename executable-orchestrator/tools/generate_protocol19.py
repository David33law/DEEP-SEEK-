"""Protocol 19 is GENERATED from the state machine — it says so on its own second line.

In v2.0 nothing enforced that, so the document could drift from the code silently and
still point at a module path that no longer existed. Here the document has exactly one
producer, and validate_package.py fails if the file on disk differs by a single byte
from what this generator emits. Documentation drift stops being a discipline problem and
becomes a structurally impossible state.

    --check   compare only, exit 1 on drift
    (default) rewrite the document
"""
