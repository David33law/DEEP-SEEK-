def render():
    lines = [
        "# 19 — DEEPSEEK RUNNER STATE MACHINE (v2.1)",
        "",
        f"Source of truth: {SOURCE_OF_TRUTH} — this document is GENERATED by",
        "executable-orchestrator/tools/generate_protocol19.py and validate_package.py fails on any drift.",
        "",
        "Every transition requires, in order: (1) legality from the state derived from the SIGNED event",
        "log, (2) the declared artifact validating against its JSON Schema, (3) the state's semantic",
        "predicate, (4) for owner gates, an owner-signed approval bound to gate, run and artifact hash.",
        "File existence alone advances nothing.",
        "",
        "## States",
        "",
    ]
    for s in STATES:
        nxt = ", ".join(NEXT.get(s, [])) or "—"
        gate = OWNER_GATES.get(s)
        marks = []
        if s in SCHEMAS:
            marks.append("schema-guarded")
        if s in SEMANTIC:
            marks.append("semantic-guarded")
        if gate:
            marks.append(f"owner-gate:{gate}")
        lines.append(f"- **{s}** — {NOTES.get(s, '')} | next: {nxt} | guards: "
                     f"{', '.join(marks) if marks else 'log-legality only'}")
    lines += [
        "",
        "## Terminal honesty",
        "",
        "COMMITTED is not the only acceptable ending. BEST_DISCOVERED_SO_FAR and HALTED are first-class:",
        "a run that did not reach the target must say so rather than relabel a lesser result.",
        "",
    ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    want = render()
    if a.check:
        have = open(TARGET, encoding="utf-8").read() if os.path.exists(TARGET) else ""
        if have != want:
            print("PROTOCOL 19 DRIFT: the document does not match the state machine")
            return 1
        print("protocol 19: in sync with the state machine")
        return 0
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(want)
    print(f"protocol 19 regenerated from {SOURCE_OF_TRUTH} ({len(STATES)} states)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
